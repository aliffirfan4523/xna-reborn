using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using XnaReborn.Core.Models;
using XnaReborn.Flash.Analyzer.As3;
using XnaReborn.Flash.Analyzer.Reading;
using XnaReborn.Flash.Analyzer.Resolving;

namespace XnaReborn.Flash.Converter;

/// <summary>One marker left in converted code.</summary>
/// <param name="RuleId">The FL rule id, or FL000 for problems that have no rule.</param>
/// <param name="File">Relative path of the AS3 file.</param>
/// <param name="Line">1-based line in the AS3 file.</param>
public sealed record ConversionMarker(string RuleId, string File, int Line);

/// <summary>The C# text made from one AS3 file.</summary>
/// <param name="Text">The C# source.</param>
/// <param name="Markers">Markers written into it.</param>
public sealed record EmittedFile(string Text, IReadOnlyList<ConversionMarker> Markers);

/// <summary>Where an <c>[Embed]</c> field gets its asset from in the converted game.</summary>
/// <param name="ContentName">The name passed to the runtime: content name for textures and sounds, file path for data.</param>
/// <param name="Kind">Asset kind name from the runtime enum: Texture, Sound, Song or Data.</param>
public sealed record EmbedBinding(string ContentName, string Kind);

/// <summary>
/// Writes C# for the AS3 of a Flash project. It handles the language gaps of the spec table (int division, NaN defaults, closures,
/// class values, Vector, Object bags) and leaves a marker comment wherever a person must decide.
/// </summary>
public sealed class CSharpEmitter
{
    private static readonly HashSet<string> _csKeywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue", "decimal",
        "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally", "fixed", "float",
        "for", "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock", "long", "namespace", "new",
        "null", "object", "operator", "out", "override", "params", "private", "protected", "public", "readonly", "ref", "return",
        "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try",
        "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
    };

    private static readonly Dictionary<string, string> _unsupportedRules = new(StringComparer.Ordinal)
    {
        ["with"] = "FL020",
        ["e4x"] = "FL021",
        ["namespace"] = "FL025",
        ["regex"] = "FL030",
        ["include"] = "FL025",
    };

    private readonly FlashProject _project;
    private readonly As3TypeResolver _resolver;
    private readonly IReadOnlyDictionary<(string File, string Field), EmbedBinding> _embeds;
    private readonly IReadOnlyList<Finding> _findings;

    private readonly StringBuilder _sb = new();
    private readonly List<ConversionMarker> _markers = new();
    private readonly HashSet<Finding> _claimed = new();
    private readonly List<HashSet<string>> _declared = new();
    private FlashSourceFile _file = null!;
    private As3TypeDeclaration? _class;
    private As3Scope _scope = new(null, new Dictionary<string, string?>());
    private string? _returnType;
    private int _indent;

    /// <summary>Creates an emitter for a project.</summary>
    /// <param name="project">The project.</param>
    /// <param name="embeds">Asset bindings by (relative .as file, field name).</param>
    /// <param name="findings">Analyzer findings; manual ones become markers.</param>
    public CSharpEmitter(
        FlashProject project,
        IReadOnlyDictionary<(string File, string Field), EmbedBinding> embeds,
        IReadOnlyList<Finding> findings)
    {
        _project = project ?? throw new ArgumentNullException(nameof(project));
        _embeds = embeds ?? throw new ArgumentNullException(nameof(embeds));
        _findings = findings ?? throw new ArgumentNullException(nameof(findings));
        _resolver = new As3TypeResolver(project.Files);
    }

    /// <summary>Converts one file.</summary>
    /// <param name="file">A project file that is not part of a bundled Flixel.</param>
    public EmittedFile Emit(FlashSourceFile file)
    {
        ArgumentNullException.ThrowIfNull(file);
        _file = file;
        _sb.Clear();
        _markers.Clear();
        _claimed.Clear();
        _indent = 0;
        var unit = file.Unit;

        Line($"// <auto-generated> Converted from {file.Path} by XNA Reborn. Lines starting with XNAREBORN: need a person. </auto-generated>");
        Line("using System;");
        Line("using System.Collections.Generic;");
        Line("using org.flixel;");
        Line("using XnaReborn.As3;");
        Line("using static XnaReborn.As3.AsGlobals;");
        var usings = new HashSet<string>(StringComparer.Ordinal);
        foreach (var import in unit.Imports)
        {
            WriteMarkers(import);
            var ns = import.IsWildcard ? import.Name : (import.Name.Contains('.') ? import.Name[..import.Name.LastIndexOf('.')] : string.Empty);
            if (ns.Length > 0 && ns != "org.flixel" && !IsPlatformNamespace(ns) && usings.Add(ns))
            {
                Line($"using {ns};");
            }
        }

        Line(string.Empty);
        var hasNamespace = unit.PackageName.Length > 0;
        if (hasNamespace)
        {
            Line($"namespace {unit.PackageName}");
            Line("{");
            _indent++;
        }

        foreach (var member in unit.Members)
        {
            EmitTopLevel(member);
        }

        if (hasNamespace)
        {
            _indent--;
            Line("}");
        }

        return new EmittedFile(_sb.ToString(), _markers.ToList());
    }

    private static bool IsPlatformNamespace(string ns) => ns.StartsWith("flash.", StringComparison.Ordinal) || ns == "flash";

    // ------------------------------------------------------------------ output helpers

    private void Line(string text)
    {
        if (text.Length > 0)
        {
            _sb.Append(' ', _indent * 4);
        }

        _sb.Append(text).Append('\n');
    }

    // Points compiler messages for the lines that follow at the AS3 line they came from (task 15.2). The path is the project-relative .as path.
    private void Mark(As3Node node) =>
        _sb.Append("#line ").Append(node.Span.Line).Append(" \"").Append(_file.Path.Replace('\\', '/')).Append("\"\n");

    private void Marker(string ruleId, int line, string message, string? original)
    {
        _markers.Add(new ConversionMarker(ruleId, _file.Path, line));
        Line($"// XNAREBORN: {ruleId} {message}".TrimEnd());
        if (!string.IsNullOrWhiteSpace(original))
        {
            foreach (var l in original.Split('\n'))
            {
                Line("// " + l.TrimEnd('\r').TrimEnd());
            }
        }
    }

    private int EndLine(As3Node node)
    {
        var text = _file.Text;
        var start = Math.Clamp(node.Span.Start, 0, text.Length);
        var length = Math.Clamp(node.Span.Length, 0, text.Length - start);
        var lines = 0;
        for (var i = start; i < start + length; i++)
        {
            if (text[i] == '\n')
            {
                lines++;
            }
        }

        return node.Span.Line + lines;
    }

    // Writes a marker for each manual finding that sits on the node's lines and was not written yet.
    private void WriteMarkers(As3Node node, bool headerOnly = false)
    {
        var first = node.Span.Line;
        var last = headerOnly ? first : EndLine(node);
        foreach (var f in _findings)
        {
            if (f.Location is null || f.Location.File != _file.Path || f.Location.Line < first || f.Location.Line > last || _claimed.Contains(f))
            {
                continue;
            }

            if (f.Classification == Classification.AutoFixable && f.RuleId != "FL023")
            {
                continue;
            }

            _claimed.Add(f);
            Marker(f.RuleId, f.Location.Line, f.Title + ".", f.Snippet is null ? null : "Original AS3: " + f.Snippet);
        }
    }

    private static string Esc(string name) => _csKeywords.Contains(name) ? "@" + name : name;

    // ------------------------------------------------------------------ types

    private static string MapType(As3TypeRef? t)
    {
        if (t is null || t.Name == "*")
        {
            return "dynamic";
        }

        if (t.TypeArguments.Count > 0)
        {
            var args = string.Join(", ", t.TypeArguments.Select(MapType));
            return t.Name == "Vector" ? $"AsVector<{args}>" : $"{t.Name}<{args}>";
        }

        return MapTypeName(t.Name);
    }

    private static string MapTypeName(string name) => name switch
    {
        "Number" => "double",
        "Boolean" => "bool",
        "String" => "string",
        "Object" => "AsObject",
        "Array" => "AsArray",
        "Function" => "AsFunction",
        "Class" => "AsClass",
        "Dictionary" or "flash.utils.Dictionary" => "AsDictionary",
        "Error" => "Exception",
        "Date" => "DateTime",
        "XML" or "XMLList" or "RegExp" => "object",
        "int" or "uint" or "void" => name,
        _ => name,
    };

    private string MapTypeText(string? resolved)
    {
        if (resolved is null)
        {
            return "dynamic";
        }

        if (resolved.StartsWith("Vector.<", StringComparison.Ordinal))
        {
            return "AsVector<" + string.Join(", ", resolved[8..^1].Split(',').Select(a => MapTypeName(a))) + ">";
        }

        return MapTypeName(resolved);
    }

    private static bool IsValueType(string? t) => t is "int" or "uint" or "Number" or "Boolean";

    // ------------------------------------------------------------------ declarations

    private void EmitTopLevel(As3Member member)
    {
        switch (member)
        {
            case As3TypeDeclaration t:
                EmitType(t);
                break;
            case As3UnsupportedMember u:
                WriteUnsupportedMember(u);
                break;
            default:
                Marker("FL000", member.Span.Line, "Package-level functions and variables are not converted.", RawOf(member));
                break;
        }
    }

    private string RawOf(As3Node n)
    {
        var s = n.Span;
        return _file.Text.Substring(Math.Clamp(s.Start, 0, _file.Text.Length), Math.Min(s.Length, _file.Text.Length - Math.Clamp(s.Start, 0, _file.Text.Length)));
    }

    private void WriteUnsupportedMember(As3UnsupportedMember u)
    {
        var rule = _unsupportedRules.GetValueOrDefault(u.Reason, "FL000");
        if (!_claimed.Any(c => c.RuleId == rule && c.Location?.Line == u.Span.Line))
        {
            Marker(rule, u.Span.Line, $"{u.Reason} is not supported.", u.RawText);
        }
    }

    private static string Access(As3Modifier m)
    {
        if ((m & As3Modifier.Public) != 0)
        {
            return "public ";
        }

        if ((m & As3Modifier.Private) != 0)
        {
            return "private ";
        }

        if ((m & As3Modifier.Protected) != 0)
        {
            return "protected ";
        }

        return "internal ";
    }

    private void EmitType(As3TypeDeclaration t)
    {
        var saveClass = _class;
        _class = t;
        Mark(t);
        WriteMarkers(t, headerOnly: true);
        var bases = new List<string>();
        if (t.BaseType is not null)
        {
            bases.Add(MapType(t.BaseType));
        }

        bases.AddRange(t.Interfaces.Select(MapType));
        var inherit = bases.Count > 0 ? " : " + string.Join(", ", bases) : string.Empty;
        var sealedText = (t.Modifiers & As3Modifier.Final) != 0 && t.Kind == As3TypeKind.Class ? "sealed " : string.Empty;
        var kind = t.Kind == As3TypeKind.Class ? "class" : "interface";
        var access = (t.Modifiers & As3Modifier.Public) != 0 || t.Kind == As3TypeKind.Interface ? "public " : "internal ";
        Line($"{access}{sealedText}{kind} {Esc(t.Name)}{inherit}");
        Line("{");
        _indent++;
        EmitMembers(t);
        _indent--;
        Line("}");
        Line(string.Empty);
        _class = saveClass;
    }

    private void EmitMembers(As3TypeDeclaration t)
    {
        var done = new HashSet<As3Member>();
        foreach (var m in t.Members)
        {
            if (done.Contains(m))
            {
                continue;
            }

            switch (m)
            {
                case As3Field f:
                    EmitField(f);
                    break;
                case As3Method { Kind: As3MethodKind.Getter or As3MethodKind.Setter } acc:
                    var partner = t.Members.OfType<As3Method>().FirstOrDefault(o => o != acc && o.Name == acc.Name
                        && o.Kind is As3MethodKind.Getter or As3MethodKind.Setter && (o.Modifiers & As3Modifier.Static) == (acc.Modifiers & As3Modifier.Static));
                    if (partner is not null)
                    {
                        done.Add(partner);
                    }

                    EmitProperty(t, acc, partner);
                    break;
                case As3Method method:
                    EmitMethod(t, method);
                    break;
                case As3UnsupportedMember u:
                    WriteUnsupportedMember(u);
                    break;
                case As3TypeDeclaration inner:
                    EmitType(inner);
                    break;
            }

            done.Add(m);
        }
    }

    private void EmitField(As3Field f)
    {
        Mark(f);
        WriteMarkers(f);
        var access = Access(f.Modifiers);
        var isStatic = (f.Modifiers & As3Modifier.Static) != 0 ? "static " : string.Empty;
        if (f.Metadata.Any(m => m.Name == "Embed") && _embeds.TryGetValue((_file.Path, f.Name), out var binding))
        {
            Line($"{access}{isStatic}AsClass {Esc(f.Name)} = AsClass.FromAsset({CsString(binding.ContentName)}, AssetKind.{binding.Kind});");
            return;
        }

        if (f.Metadata.Any(m => m.Name == "Embed"))
        {
            Line($"{access}{isStatic}AsClass {Esc(f.Name)} = AsClass.FromAsset(string.Empty, AssetKind.Data);");
            return;
        }

        var type = MapType(f.Type);
        var typeName = As3TypeResolver.TypeName(f.Type);
        _scope = new As3Scope(_class, new Dictionary<string, string?>());
        string init;
        if (f.Initializer is not null)
        {
            init = " = " + Convert(f.Initializer, typeName);
        }
        else if (typeName == "Number")
        {
            init = " = double.NaN";
        }
        else
        {
            init = string.Empty;
        }

        var isConst = f.IsConst && f.Initializer is As3Literal && typeName is "int" or "uint" or "Number" or "String" or "Boolean";
        if (isConst && f.Initializer is As3Literal)
        {
            Line($"{access}{isStatic.Replace("static ", string.Empty)}const {type} {Esc(f.Name)}{init};");
        }
        else
        {
            var ro = f.IsConst ? "readonly " : string.Empty;
            Line($"{access}{isStatic}{ro}{type} {Esc(f.Name)}{init};");
        }
    }

    private string Params(IReadOnlyList<As3Parameter> parameters)
    {
        var list = new List<string>();
        foreach (var p in parameters)
        {
            if (p.IsRest)
            {
                list.Add($"params object[] {Esc(p.Name)}");
                continue;
            }

            var type = MapType(p.Type);
            var def = string.Empty;
            if (p.Default is not null)
            {
                def = p.Default is As3Literal or As3Unary { Operand: As3Literal } ? " = " + Convert(p.Default, As3TypeResolver.TypeName(p.Type)) : " = default";
            }

            list.Add($"{type} {Esc(p.Name)}{def}");
        }

        return string.Join(", ", list);
    }

    private string MethodHeaderModifiers(As3TypeDeclaration t, As3Modifier m, bool allowVirtual)
    {
        var sb = new StringBuilder(Access(m));
        if ((m & As3Modifier.Static) != 0)
        {
            sb.Append("static ");
        }
        else if ((m & As3Modifier.Override) != 0)
        {
            sb.Append((m & As3Modifier.Final) != 0 ? "sealed override " : "override ");
        }
        else if (t.Kind == As3TypeKind.Class && allowVirtual && (m & (As3Modifier.Private | As3Modifier.Final)) == 0 && (t.Modifiers & As3Modifier.Final) == 0)
        {
            sb.Append("virtual ");
        }

        return sb.ToString();
    }

    private void EmitMethod(As3TypeDeclaration t, As3Method m)
    {
        Mark(m);
        WriteMarkers(m, headerOnly: true);
        _scope = As3TypeResolver.ScopeFor(t, m.Parameters, m.Body);
        _returnType = As3TypeResolver.TypeName(m.ReturnType);
        _declared.Clear();
        _declared.Add(new HashSet<string>(m.Parameters.Select(p => p.Name), StringComparer.Ordinal));

        if (t.Kind == As3TypeKind.Interface)
        {
            Line($"{MapReturn(m)} {Esc(m.Name)}({Params(m.Parameters)});");
            return;
        }

        if (m.Kind == As3MethodKind.Constructor)
        {
            var body = m.Body?.Statements ?? [];
            var initializer = string.Empty;
            var skip = 0;
            if (body.Count > 0 && body[0] is As3ExpressionStatement { Expression: As3Call { Target: As3Identifier { Name: "super" } } sup })
            {
                initializer = " : base(" + Args(sup.Arguments) + ")";
                skip = 1;
            }

            Line($"{Access(m.Modifiers)}{Esc(t.Name)}({Params(m.Parameters)}){initializer}");
            EmitBlockBody(body.Skip(skip).ToList());
            return;
        }

        var mods = MethodHeaderModifiers(t, m.Modifiers, allowVirtual: true);
        Line($"{mods}{MapReturn(m)} {Esc(m.Name)}({Params(m.Parameters)})");
        if (m.Body is null)
        {
            Line("{");
            Line("}");
            return;
        }

        EmitBlockBody(m.Body.Statements);
    }

    private static string MapReturn(As3Method m) => m.ReturnType is null ? "dynamic" : MapType(m.ReturnType);

    private void EmitProperty(As3TypeDeclaration t, As3Method first, As3Method? second)
    {
        var getter = first.Kind == As3MethodKind.Getter ? first : second;
        var setter = first.Kind == As3MethodKind.Setter ? first : second;
        var typeRef = getter?.ReturnType ?? setter?.Parameters.FirstOrDefault()?.Type;
        var typeName = As3TypeResolver.TypeName(typeRef);
        var mods = MethodHeaderModifiers(t, first.Modifiers, allowVirtual: true);
        Mark(first);
        WriteMarkers(first, headerOnly: true);
        if (t.Kind == As3TypeKind.Interface)
        {
            Line($"{MapType(typeRef)} {Esc(first.Name)} {{ {(getter is not null ? "get; " : string.Empty)}{(setter is not null ? "set; " : string.Empty)}}}");
            return;
        }

        Line($"{mods}{MapType(typeRef)} {Esc(first.Name)}");
        Line("{");
        _indent++;
        foreach (var (accessor, isGet) in new[] { (getter, true), (setter, false) })
        {
            if (accessor?.Body is null)
            {
                continue;
            }

            _scope = As3TypeResolver.ScopeFor(t, accessor.Parameters, accessor.Body);
            _returnType = isGet ? typeName : "void";
            _declared.Clear();
            _declared.Add(new HashSet<string>(accessor.Parameters.Select(p => p.Name), StringComparer.Ordinal));
            Line(isGet ? "get" : "set");
            Line("{");
            _indent++;
            if (!isGet && accessor.Parameters.Count > 0)
            {
                Line($"{MapType(accessor.Parameters[0].Type)} {Esc(accessor.Parameters[0].Name)} = value;");
            }

            EmitStatements(accessor.Body.Statements);
            _indent--;
            Line("}");
        }

        _indent--;
        Line("}");
    }

    // ------------------------------------------------------------------ statements

    private void EmitBlockBody(IReadOnlyList<As3Statement> statements)
    {
        Line("{");
        _indent++;
        EmitStatements(statements);
        _indent--;
        Line("}");
    }

    private void EmitStatements(IEnumerable<As3Statement> statements)
    {
        foreach (var s in statements)
        {
            EmitStatement(s);
        }
    }

    private void EmitBody(As3Statement body)
    {
        _declared.Add(new HashSet<string>(StringComparer.Ordinal));
        if (body is As3Block b)
        {
            EmitBlockBody(b.Statements);
        }
        else
        {
            Line("{");
            _indent++;
            EmitStatement(body);
            _indent--;
            Line("}");
        }

        _declared.RemoveAt(_declared.Count - 1);
    }

    private bool IsDeclared(string name) => _declared.Any(s => s.Contains(name));

    private void EmitStatement(As3Statement s)
    {
        if (s is not (As3Block or As3EmptyStatement))
        {
            Mark(s);
        }

        switch (s)
        {
            case As3Block b:
                _declared.Add(new HashSet<string>(StringComparer.Ordinal));
                EmitBlockBody(b.Statements);
                _declared.RemoveAt(_declared.Count - 1);
                break;
            case As3EmptyStatement:
                break;
            case As3VarStatement v:
                WriteMarkers(v);
                foreach (var d in v.Declarators)
                {
                    EmitDeclarator(d);
                }

                break;
            case As3ExpressionStatement e:
                WriteMarkers(e);
                EmitExpressionStatement(e.Expression);
                break;
            case As3IfStatement i:
                WriteMarkers(i, headerOnly: true);
                Line($"if ({Cond(i.Condition)})");
                EmitBody(i.Then);
                if (i.Else is As3IfStatement)
                {
                    Line("else");
                    EmitBody(new As3Block(i.Else.Span, [i.Else]));
                }
                else if (i.Else is not null)
                {
                    Line("else");
                    EmitBody(i.Else);
                }

                break;
            case As3WhileStatement w:
                WriteMarkers(w, headerOnly: true);
                Line($"while ({Cond(w.Condition)})");
                EmitBody(w.Body);
                break;
            case As3DoStatement d:
                Line("do");
                EmitBody(d.Body);
                Line($"while ({Cond(d.Condition)});");
                break;
            case As3ForStatement f:
                EmitFor(f);
                break;
            case As3ForInStatement fi:
                EmitForIn(fi);
                break;
            case As3SwitchStatement sw:
                EmitSwitch(sw);
                break;
            case As3TryStatement t:
                Line("try");
                EmitBody(t.Body);
                foreach (var c in t.Catches)
                {
                    var type = c.Type is null || c.Type.Name == "*" ? "Exception" : MapType(c.Type);
                    Line($"catch ({type} {Esc(c.Name)})");
                    EmitBody(c.Body);
                }

                if (t.Finally is not null)
                {
                    Line("finally");
                    EmitBody(t.Finally);
                }

                break;
            case As3ReturnStatement r:
                WriteMarkers(r);
                Line(r.Value is null ? "return;" : $"return {Convert(r.Value, _returnType)};");
                break;
            case As3ThrowStatement th:
                WriteMarkers(th);
                Line($"throw AsOps.ToException({Expr(th.Value)});");
                break;
            case As3BreakStatement { Label: null }:
                Line("break;");
                break;
            case As3ContinueStatement { Label: null }:
                Line("continue;");
                break;
            case As3BreakStatement br:
                Marker("FL000", br.Span.Line, "Labeled break is not converted.", RawOf(br));
                break;
            case As3ContinueStatement co:
                Marker("FL000", co.Span.Line, "Labeled continue is not converted.", RawOf(co));
                break;
            case As3LabeledStatement l:
                Marker("FL000", l.Span.Line, "Labels are not converted.", null);
                EmitStatement(l.Body);
                break;
            case As3UnsupportedStatement u:
                var rule = _unsupportedRules.GetValueOrDefault(u.Reason, "FL000");
                var message = u.Reason == "syntax-error" ? "This statement did not parse and was left out." : $"{u.Reason} is not supported.";
                if (!_claimed.Any(c => c.RuleId == rule && c.Location?.Line >= u.Span.Line && c.Location?.Line <= EndLine(u)))
                {
                    Marker(rule, u.Span.Line, message, u.RawText);
                }
                else
                {
                    WriteMarkers(u);
                    Line("// " + RawOf(u).Replace("\n", " ").Trim());
                }

                break;
            default:
                Marker("FL000", s.Span.Line, "Unknown statement.", RawOf(s));
                break;
        }
    }

    private void EmitDeclarator(As3Declarator d)
    {
        var typeName = As3TypeResolver.TypeName(d.Type);
        var already = IsDeclared(d.Name);
        string value;
        if (d.Initializer is not null)
        {
            value = Convert(d.Initializer, typeName);
        }
        else if (typeName == "Number")
        {
            value = "double.NaN";
        }
        else
        {
            value = "default";
        }

        if (already)
        {
            if (d.Initializer is not null)
            {
                Line($"{Esc(d.Name)} = {value};");
            }

            return;
        }

        _declared[^1].Add(d.Name);
        var suffix = d.Type is null || d.Type.Name == "*" ? " // XNAREBORN: FL023 untyped variable became dynamic" : string.Empty;
        if (suffix.Length > 0)
        {
            _markers.Add(new ConversionMarker("FL023", _file.Path, d.Span.Line));
        }

        Line($"{MapType(d.Type)} {Esc(d.Name)} = {value};{suffix}");
    }

    private void EmitExpressionStatement(As3Expression e)
    {
        switch (e)
        {
            case As3Call or As3Assignment or As3New or As3Unary { Operator: "++" or "--" or "delete" }:
                Line(Expr(e) + ";");
                break;
            case As3FunctionExpression { Name: not null } named:
                Line($"AsFunction {Esc(named.Name)} = {Expr(named with { Name = null })};");
                break;
            case As3Binary { Operator: "," } comma:
                EmitExpressionStatement(comma.Left);
                EmitExpressionStatement(comma.Right);
                break;
            case As3UnsupportedExpression u:
                Marker(_unsupportedRules.GetValueOrDefault(u.Reason, "FL000"), u.Span.Line, $"{u.Reason} is not supported.", u.RawText);
                break;
            default:
                Line($"_ = {Expr(e)};");
                break;
        }
    }

    private void EmitFor(As3ForStatement f)
    {
        WriteMarkers(f, headerOnly: true);
        _declared.Add(new HashSet<string>(StringComparer.Ordinal));
        var init = string.Empty;
        switch (f.Initializer)
        {
            case As3VarStatement v when v.Declarators.Count > 0 && v.Declarators.All(d => !IsDeclared(d.Name)):
                {
                    var type = MapType(v.Declarators[0].Type);
                    var parts = new List<string>();
                    foreach (var d in v.Declarators)
                    {
                        _declared[^1].Add(d.Name);
                        var tn = As3TypeResolver.TypeName(d.Type);
                        parts.Add($"{Esc(d.Name)} = {(d.Initializer is null ? (tn == "Number" ? "double.NaN" : "default") : Convert(d.Initializer, tn))}");
                    }

                    init = $"{type} {string.Join(", ", parts)}";
                    break;
                }

            case As3VarStatement v2:
                init = string.Join(", ", v2.Declarators.Where(d => d.Initializer is not null).Select(d => $"{Esc(d.Name)} = {Convert(d.Initializer!, As3TypeResolver.TypeName(d.Type))}"));
                break;
            case As3ExpressionStatement es:
                init = CommaList(es.Expression);
                break;
        }

        var cond = f.Condition is null ? string.Empty : Cond(f.Condition);
        var inc = f.Increment is null ? string.Empty : CommaList(f.Increment);
        Line($"for ({init}; {cond}; {inc})");
        EmitBody(f.Body);
        _declared.RemoveAt(_declared.Count - 1);
    }

    private string CommaList(As3Expression e) =>
        e is As3Binary { Operator: "," } c ? CommaList(c.Left) + ", " + CommaList(c.Right) : Expr(e);

    private void EmitForIn(As3ForInStatement fi)
    {
        WriteMarkers(fi, headerOnly: true);
        _declared.Add(new HashSet<string>(StringComparer.Ordinal));
        string variable;
        if (fi.Variable is { } v)
        {
            _declared[^1].Add(v.Name);
            var vt = v.Type is null || v.Type.Name == "*" ? "dynamic" : MapType(v.Type);
            if (!fi.IsEach && v.Type is null)
            {
                vt = "string";
            }

            variable = $"{vt} {Esc(v.Name)}";
        }
        else
        {
            var name = fi.Target is As3Identifier id ? Esc(id.Name) : "__item";
            variable = $"var {name}__loop";
            Marker("FL000", fi.Span.Line, "For-in over an existing variable is approximated.", null);
        }

        var collection = Expr(fi.Collection);
        var source = fi.IsEach ? $"AsOps.ValuesOf({collection})" : $"AsOps.KeysOf({collection})";
        if (fi.IsEach && _resolver.TypeOf(fi.Collection, _scope) is { } ct && (ct.StartsWith("Vector.<", StringComparison.Ordinal) || ct == "Array"))
        {
            source = collection;
        }

        Line($"foreach ({variable} in {source})");
        if (fi.Variable is null && fi.Target is As3Identifier tid)
        {
            Line("{");
            _indent++;
            Line($"{Esc(tid.Name)} = {Esc(tid.Name)}__loop;");
            _indent--;
            EmitBlockBody(fi.Body is As3Block bb ? bb.Statements : [fi.Body]);
            Line("}");
        }
        else
        {
            EmitBody(fi.Body);
        }

        _declared.RemoveAt(_declared.Count - 1);
    }

    private void EmitSwitch(As3SwitchStatement sw)
    {
        WriteMarkers(sw, headerOnly: true);
        Line($"switch ({Expr(sw.Discriminant)})");
        Line("{");
        _indent++;
        _declared.Add(new HashSet<string>(StringComparer.Ordinal));
        for (var i = 0; i < sw.Cases.Count; i++)
        {
            var c = sw.Cases[i];
            Line(c.Test is null ? "default:" : $"case {Expr(c.Test)}:");
            if (c.Statements.Count == 0)
            {
                continue;
            }

            _indent++;
            EmitStatements(c.Statements);
            var last = c.Statements[^1];
            var terminated = last is As3BreakStatement or As3ReturnStatement or As3ThrowStatement or As3ContinueStatement;
            if (!terminated)
            {
                if (i + 1 < sw.Cases.Count)
                {
                    var next = sw.Cases[i + 1];
                    Line(next.Test is null ? "goto default;" : $"goto case {Expr(next.Test)};");
                }
                else
                {
                    Line("break;");
                }
            }

            _indent--;
        }

        _declared.RemoveAt(_declared.Count - 1);
        _indent--;
        Line("}");
    }

    // ------------------------------------------------------------------ expressions

    private string? TypeOf(As3Expression e) => _resolver.TypeOf(e, _scope);

    private string Args(IEnumerable<As3Expression> args) => string.Join(", ", args.Select(Expr));

    /// <summary>Emits <paramref name="e"/> converted to <paramref name="target"/> (an AS3 type name) when a cast is needed.</summary>
    private string Convert(As3Expression e, string? target)
    {
        var code = Expr(e);
        var from = TypeOf(e);
        if (target is "int" or "uint" && As3TypeResolver.IsNumeric(from) && from != target && !(e is As3Literal && from is "int" or "uint"))
        {
            return $"({target})({code})";
        }

        if (target == "Boolean" && from != "Boolean")
        {
            return Cond(e);
        }

        return code;
    }

    private string Cond(As3Expression e)
    {
        if (e is As3Binary { Operator: "&&" or "||" or "==" or "!=" or "===" or "!==" or "<" or ">" or "<=" or ">=" or "is" or "in" or "instanceof" } or As3Unary { Operator: "!" })
        {
            return Expr(e);
        }

        if (e is As3Parenthesized p)
        {
            return Cond(p.Inner);
        }

        var t = TypeOf(e);
        var code = Expr(e);
        return t switch
        {
            "Boolean" => code,
            "int" or "uint" => $"{Operand(e)} != 0",
            "String" => $"!string.IsNullOrEmpty({code})",
            null => $"AsOps.ToBoolean({code})",
            "Number" => $"AsOps.ToBoolean({code})",
            _ => $"{Operand(e)} != null",
        };
    }

    private string Operand(As3Expression e)
    {
        var code = Expr(e);
        return e is As3Binary or As3Conditional or As3Assignment or As3Unary or As3FunctionExpression or As3UnsupportedExpression { Reason: not "e4x" } ? $"({code})" : code;
    }

    private string Expr(As3Expression e)
    {
        switch (e)
        {
            case As3Literal l:
                return Literal(l);
            case As3Identifier id:
                return IdentifierValue(id);
            case As3Parenthesized p:
                return "(" + Expr(p.Inner) + ")";
            case As3MemberAccess m:
                return MemberAccess(m);
            case As3IndexAccess ix:
                {
                    var tt = TypeOf(ix.Target);
                    var idxType = TypeOf(ix.Index);
                    var idx = Expr(ix.Index);
                    if (tt is not null && (tt == "Array" || tt.StartsWith("Vector.<", StringComparison.Ordinal)) && idxType is "Number")
                    {
                        idx = $"(int)({idx})";
                    }

                    return $"{Operand(ix.Target)}[{idx}]";
                }

            case As3GenericExpression g:
                return $"AsClass.Of<{MapType(new As3TypeRef(g.Span, ExprName(g.Target), g.TypeArguments))}>()";
            case As3Call c:
                return Call(c);
            case As3New n:
                return New(n);
            case As3Unary u:
                return Unary(u);
            case As3Binary b:
                return Binary(b);
            case As3Assignment a:
                return Assignment(a);
            case As3Conditional c:
                return $"{Cond(c.Condition)} ? {Operand(c.WhenTrue)} : {Operand(c.WhenFalse)}";
            case As3ArrayLiteral arr:
                return arr.Elements.Count == 0 ? "new AsArray()" : $"new AsArray({Args(arr.Elements)})";
            case As3ObjectLiteral o:
                return o.Properties.Count == 0
                    ? "new AsObject()"
                    : "new AsObject { " + string.Join(", ", o.Properties.Select(p => $"[{CsString(p.Key)}] = {Expr(p.Value)}")) + " }";
            case As3FunctionExpression f:
                return FunctionExpr(f);
            case As3UnsupportedExpression u:
                {
                    var rule = _unsupportedRules.GetValueOrDefault(u.Reason, "FL000");
                    _markers.Add(new ConversionMarker(rule, _file.Path, u.Span.Line));
                    var raw = u.RawText.Replace("*/", "* /", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);
                    return $"((dynamic)null /* XNAREBORN: {rule} {u.Reason} is not supported: {raw} */)";
                }

            default:
                return "default";
        }
    }

    private static string ExprName(As3Expression e) => e switch
    {
        As3Identifier i => i.Name,
        As3MemberAccess m => ExprName(m.Target) + "." + m.Name,
        _ => "object",
    };

    private string Literal(As3Literal l)
    {
        switch (l.Kind)
        {
            case As3LiteralKind.Number:
                return l.Text.StartsWith('.') ? "0" + l.Text : l.Text;
            case As3LiteralKind.String:
                return CsString(UnescapeAs3(l.Text));
            case As3LiteralKind.Regex:
                _markers.Add(new ConversionMarker("FL030", _file.Path, l.Span.Line));
                return $"((dynamic)null /* XNAREBORN: FL030 regular expression {l.Text.Replace("*/", "* /", StringComparison.Ordinal)} */)";
            default:
                return l.Text;
        }
    }

    private static string CsString(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static string UnescapeAs3(string literal)
    {
        var body = literal.Length >= 2 ? literal[1..^1] : literal;
        var sb = new StringBuilder();
        for (var i = 0; i < body.Length; i++)
        {
            var c = body[i];
            if (c != '\\' || i + 1 >= body.Length)
            {
                sb.Append(c);
                continue;
            }

            var n = body[++i];
            switch (n)
            {
                case 'n': sb.Append('\n'); break;
                case 'r': sb.Append('\r'); break;
                case 't': sb.Append('\t'); break;
                case 'b': sb.Append('\b'); break;
                case 'f': sb.Append('\f'); break;
                case '0': sb.Append('\0'); break;
                case 'x' when i + 2 < body.Length + 0 && int.TryParse(body.AsSpan(i + 1, 2), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var hx):
                    sb.Append((char)hx);
                    i += 2;
                    break;
                case 'u' when i + 4 < body.Length + 0 && int.TryParse(body.AsSpan(i + 1, 4), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var ux):
                    sb.Append((char)ux);
                    i += 4;
                    break;
                default: sb.Append(n); break;
            }
        }

        return sb.ToString();
    }

    private bool IsLocal(string name) => _scope.Locals.ContainsKey(name);

    private As3Method? FindMethod(string className, string name)
    {
        var guard = 0;
        var current = className;
        while (!string.IsNullOrEmpty(current) && guard++ < 32)
        {
            var decl = _project.Files.Where(f => !f.IsFlixelSource).SelectMany(f => f.Unit.Members.OfType<As3TypeDeclaration>()).FirstOrDefault(t => t.Name == current);
            if (decl is null)
            {
                return null;
            }

            var m = decl.Members.OfType<As3Method>().FirstOrDefault(x => x.Name == name && x.Kind == As3MethodKind.Normal);
            if (m is not null)
            {
                return m;
            }

            current = As3TypeResolver.TypeName(decl.BaseType) ?? string.Empty;
        }

        return null;
    }

    private bool IsMemberOfClass(string name)
    {
        if (_class is null)
        {
            return false;
        }

        return _class.Members.Any(m => m is As3Field f && f.Name == name || m is As3Method me && me.Name == name)
            || FindMethod(_class.Name, name) is not null;
    }

    private string IdentifierValue(As3Identifier id)
    {
        switch (id.Name)
        {
            case "this":
                return "this";
            case "super":
                return "base";
            case "undefined":
                return "null";
            case "NaN":
                return "double.NaN";
            case "Infinity":
                return "double.PositiveInfinity";
        }

        if (IsLocal(id.Name))
        {
            return Esc(id.Name);
        }

        if (_class is not null && FindMethod(_class.Name, id.Name) is { } method && !_class.Members.OfType<As3Field>().Any(f => f.Name == id.Name))
        {
            return MethodReference(method);
        }

        if (!IsMemberOfClass(id.Name) && _resolver.IsClassName(id.Name) && id.Name != "Math")
        {
            return id.Name is "int" or "uint" or "Number" or "String" or "Boolean" or "Array" or "Object"
                ? $"AsClass.Of(typeof({MapTypeName(id.Name)}))"
                : $"AsClass.Of<{id.Name}>()";
        }

        return Esc(id.Name);
    }

    private string MethodReference(As3Method m)
    {
        var types = m.Parameters.Where(p => !p.IsRest).Select(p => MapType(p.Type)).ToList();
        var returns = m.ReturnType is null ? "dynamic" : MapType(m.ReturnType);
        var del = returns == "void"
            ? (types.Count == 0 ? "Action" : $"Action<{string.Join(", ", types)}>")
            : $"Func<{string.Join(", ", types.Append(returns))}>";
        return $"AsFunction.From(new {del}({Esc(m.Name)}))";
    }

    private string MemberAccess(As3MemberAccess m)
    {
        if (m.Target is As3Identifier { Name: var tn } && !IsLocal(tn))
        {
            var mapped = StaticMember(tn, m.Name);
            if (mapped is not null)
            {
                return mapped;
            }
        }

        var targetCode = m.Target is As3Identifier { Name: "super" } ? "base" : TargetCode(m.Target);
        var name = m.Name;
        var tt = TypeOf(m.Target);
        if (name == "toString")
        {
            return $"{targetCode}.ToString";
        }

        if (tt == "String")
        {
            name = name switch
            {
                "length" => "Length",
                "indexOf" => "IndexOf",
                "toUpperCase" => "ToUpperInvariant",
                "toLowerCase" => "ToLowerInvariant",
                _ => name,
            };
        }

        return $"{targetCode}.{Esc(name)}";
    }

    // The target of a member access: class names stay plain names (static access) instead of becoming class values.
    private string TargetCode(As3Expression target)
    {
        if (target is As3Identifier id && !IsLocal(id.Name) && !IsMemberOfClass(id.Name) && _resolver.IsClassName(id.Name))
        {
            return Esc(id.Name);
        }

        return Operand(target);
    }

    private static string? StaticMember(string type, string member) => (type, member) switch
    {
        ("Math", "PI") => "Math.PI",
        ("Math", "SQRT2") => "Math.Sqrt(2)",
        ("Math", "floor") => "Math.Floor",
        ("Math", "ceil") => "Math.Ceiling",
        ("Math", "abs") => "Math.Abs",
        ("Math", "max") => "Math.Max",
        ("Math", "min") => "Math.Min",
        ("Math", "sqrt") => "Math.Sqrt",
        ("Math", "sin") => "Math.Sin",
        ("Math", "cos") => "Math.Cos",
        ("Math", "tan") => "Math.Tan",
        ("Math", "atan") => "Math.Atan",
        ("Math", "atan2") => "Math.Atan2",
        ("Math", "pow") => "Math.Pow",
        ("Math", "exp") => "Math.Exp",
        ("Math", "log") => "Math.Log",
        ("Math", "random") => "AsOps.Random",
        ("Math", "round") => "AsOps.Round",
        ("int", "MAX_VALUE") => "int.MaxValue",
        ("int", "MIN_VALUE") => "int.MinValue",
        ("uint", "MAX_VALUE") => "uint.MaxValue",
        ("Number", "NaN") => "double.NaN",
        ("Number", "MAX_VALUE") => "double.MaxValue",
        ("Number", "POSITIVE_INFINITY") => "double.PositiveInfinity",
        ("Number", "NEGATIVE_INFINITY") => "double.NegativeInfinity",
        _ => null,
    };

    private string Call(As3Call c)
    {
        switch (c.Target)
        {
            case As3Identifier { Name: "super" }:
                _markers.Add(new ConversionMarker("FL000", _file.Path, c.Span.Line));
                return "((dynamic)null /* XNAREBORN: FL000 super() call that is not the first statement of a constructor */)";
            case As3Identifier id when !IsLocal(id.Name) && !IsMemberOfClass(id.Name):
                {
                    var conv = id.Name switch
                    {
                        "int" => "AsOps.ToInt",
                        "uint" => "AsOps.ToUInt",
                        "Number" => "AsOps.ToNumber",
                        "String" => "AsOps.ToAsString",
                        "Boolean" => "AsOps.ToBoolean",
                        _ => null,
                    };
                    if (conv is not null && c.Arguments.Count == 1)
                    {
                        return $"{conv}({Expr(c.Arguments[0])})";
                    }

                    if (id.Name == "Array")
                    {
                        return $"new AsArray({Args(c.Arguments)})";
                    }

                    if (_resolver.IsClassName(id.Name) && c.Arguments.Count == 1)
                    {
                        return $"(({id.Name}){Operand(c.Arguments[0])})";
                    }

                    break;
                }

            case As3GenericExpression { Target: As3Identifier { Name: "Vector" } } g when c.Arguments.Count == 1:
                return $"new AsVector<{string.Join(", ", g.TypeArguments.Select(MapType))}>((IEnumerable<{string.Join(", ", g.TypeArguments.Select(MapType))}>){Expr(c.Arguments[0])})";
            case As3MemberAccess { Target: As3Identifier { Name: "Math" }, Name: "round" } when c.Arguments.Count == 1:
                return $"AsOps.Round({Expr(c.Arguments[0])})";
        }

        var calleeType = TypeOf(c.Target);
        var callee = c.Target switch
        {
            As3Identifier id => Esc(id.Name),
            _ => Expr(c.Target),
        };
        if (calleeType == "Function" && c.Target is not As3Identifier { Name: "super" })
        {
            return $"{callee}.Call({Args(c.Arguments)})";
        }

        return $"{callee}({Args(c.Arguments)})";
    }

    private string New(As3New n)
    {
        var args = n.Arguments;
        switch (n.Target)
        {
            case As3Identifier { Name: "Object" }:
                return "new AsObject()";
            case As3Identifier { Name: "Array" }:
                return args.Count == 1 && TypeOf(args[0]) is "int" or "uint" or "Number"
                    ? $"new AsArray {{ length = (int)({Expr(args[0])}) }}"
                    : args.Count == 0 ? "new AsArray()" : $"new AsArray({Args(args)})";
            case As3Identifier { Name: "Dictionary" }:
                return "new AsDictionary()";
            case As3GenericExpression { Target: As3Identifier { Name: "Vector" } } g:
                return $"new AsVector<{string.Join(", ", g.TypeArguments.Select(MapType))}>({(args.Count == 1 ? $"(int)({Expr(args[0])})" : string.Empty)})";
            case As3Identifier id when IsLocal(id.Name) || IsMemberOfClass(id.Name):
                return $"{Esc(id.Name)}.New({Args(args)})";
            case As3Identifier id:
                return $"new {MapTypeName(id.Name)}({Args(args)})";
            case As3MemberAccess ma when TypeOf(ma) == "Class":
                return $"{Expr(ma)}.New({Args(args)})";
            default:
                return $"new {ExprName(n.Target)}({Args(args)})";
        }
    }

    private string Unary(As3Unary u)
    {
        switch (u.Operator)
        {
            case "!":
                return $"!({Cond(u.Operand)})";
            case "typeof":
                return $"AsOps.TypeOf({Expr(u.Operand)})";
            case "void":
                return "default";
            case "delete":
                return u.Operand switch
                {
                    As3IndexAccess ix => $"{Operand(ix.Target)}.delete({Expr(ix.Index)})",
                    As3MemberAccess ma => $"{Operand(ma.Target)}.delete({CsString(ma.Name)})",
                    _ => "false",
                };
            case "~":
                return TypeOf(u.Operand) is "Number" or null ? $"~(int)({Expr(u.Operand)})" : $"~{Operand(u.Operand)}";
            case "++" or "--":
                return u.IsPrefix ? $"{u.Operator}{Operand(u.Operand)}" : $"{Operand(u.Operand)}{u.Operator}";
            default:
                return $"{u.Operator}{Operand(u.Operand)}";
        }
    }

    private string Binary(As3Binary b)
    {
        var l = TypeOf(b.Left);
        var r = TypeOf(b.Right);
        switch (b.Operator)
        {
            case "&&" or "||":
                return $"{WrapCond(b.Left)} {b.Operator} {WrapCond(b.Right)}";
            case "/" when As3TypeResolver.IsInteger(l) && As3TypeResolver.IsInteger(r):
                return $"(double){Operand(b.Left)} / {Operand(b.Right)}";
            case ">>>":
                return $"AsOps.UnsignedShiftRight({Expr(b.Left)}, (int)({Expr(b.Right)}))";
            case "&" or "|" or "^" or "<<" or ">>":
                return $"{IntOperand(b.Left, l)} {b.Operator} {IntOperand(b.Right, r)}";
            case "==" or "!=" or "===" or "!==":
                {
                    var op = b.Operator.Length == 3 ? b.Operator[..2] : b.Operator;
                    var nullCompare = b.Left is As3Literal { Kind: As3LiteralKind.Null } || b.Right is As3Literal { Kind: As3LiteralKind.Null };
                    var mixed = l is not null && r is not null && l != r && !(As3TypeResolver.IsNumeric(l) && As3TypeResolver.IsNumeric(r))
                        && (IsValueType(l) || IsValueType(r) || l == "String" || r == "String");
                    if (!nullCompare && mixed)
                    {
                        return $"{(op == "!=" ? "!" : string.Empty)}AsOps.LooseEquals({Expr(b.Left)}, {Expr(b.Right)})";
                    }

                    return $"{Operand(b.Left)} {op} {Operand(b.Right)}";
                }

            case "as":
                {
                    var type = b.Right is As3Identifier ri ? ri.Name : ExprName(b.Right);
                    return IsValueType(type)
                        ? $"AsCast.To<{MapTypeName(type)}>({Expr(b.Left)})"
                        : $"{Operand(b.Left)} as {MapTypeName(type)}";
                }

            case "is":
                return $"{Operand(b.Left)} is {MapTypeName(ExprName(b.Right))}";
            case "instanceof":
                return $"{Operand(b.Left)} is {MapTypeName(ExprName(b.Right))}";
            case "in":
                return $"AsOps.In({Expr(b.Left)}, {Expr(b.Right)})";
            case ",":
                return $"{Expr(b.Left)}, {Expr(b.Right)}";
            default:
                return $"{Operand(b.Left)} {b.Operator} {Operand(b.Right)}";
        }
    }

    private string WrapCond(As3Expression e)
    {
        var code = Cond(e);
        return e is As3Binary { Operator: "&&" or "||" } || code.Contains(" ? ", StringComparison.Ordinal) ? $"({code})" : code;
    }

    private string IntOperand(As3Expression e, string? type) =>
        type is "int" or "uint" ? Operand(e) : $"(int)({Expr(e)})";

    private string Assignment(As3Assignment a)
    {
        var targetType = TypeOf(a.Target);
        var target = Expr(a.Target);
        switch (a.Operator)
        {
            case "=":
                return $"{target} = {Convert(a.Value, targetType)}";
            case "&&=" or "||=":
                return $"{target} = {target} {a.Operator[..2]} {WrapCond(a.Value)}";
            case ">>>=":
                return $"{target} = ({MapTypeText(targetType)})AsOps.UnsignedShiftRight({target}, (int)({Expr(a.Value)}))";
            case "/=" when As3TypeResolver.IsInteger(targetType) && As3TypeResolver.IsInteger(TypeOf(a.Value)):
                return $"{target} = ({MapTypeText(targetType)})((double){target} / {Operand(a.Value)})";
            default:
                return $"{target} {a.Operator} {Expr(a.Value)}";
        }
    }

    private string FunctionExpr(As3FunctionExpression f)
    {
        var saveScope = _scope;
        var saveReturn = _returnType;
        var saveDeclared = _declared.ToList();
        var inner = As3TypeResolver.ScopeFor(_class, f.Parameters, f.Body);
        _scope = new As3Scope(_class, saveScope.Locals.Concat(inner.Locals).GroupBy(kv => kv.Key).ToDictionary(g => g.Key, g => g.Last().Value));
        _returnType = As3TypeResolver.TypeName(f.ReturnType);

        var parameters = f.Parameters.Where(p => !p.IsRest).ToList();
        var types = parameters.Select(p => MapType(p.Type)).ToList();
        var hasValue = As3Walker.DescendantsAndSelf(f.Body).OfType<As3ReturnStatement>().Any(r => r.Value is not null);
        var returns = f.ReturnType is not null ? MapType(f.ReturnType) : (hasValue ? "dynamic" : "void");
        var del = returns == "void"
            ? (types.Count == 0 ? "Action" : $"Action<{string.Join(", ", types)}>")
            : $"Func<{string.Join(", ", types.Append(returns))}>";
        var paramText = string.Join(", ", parameters.Select(p => $"{MapType(p.Type)} {Esc(p.Name)}"));

        var outer = _sb.ToString();
        var saveSb = new StringBuilder(outer);
        _sb.Clear();
        var saveIndent = _indent;
        _indent = 0;
        _declared.Clear();
        _declared.Add(new HashSet<string>(parameters.Select(p => p.Name), StringComparer.Ordinal));
        EmitBlockBody(f.Body.Statements);
        var body = _sb.ToString().TrimEnd('\n');
        _sb.Clear();
        _sb.Append(saveSb);
        _indent = saveIndent;
        _declared.Clear();
        _declared.AddRange(saveDeclared);
        _scope = saveScope;
        _returnType = saveReturn;

        // The block text is indented relative to column 0; indent continuation lines to match the current level.
        var pad = new string(' ', _indent * 4);
        body = string.Join("\n", body.Split('\n').Select((l, i) => i == 0 ? l : pad + l));
        return $"AsFunction.From(new {del}(({paramText}) =>\n{pad}{body}))";
    }
