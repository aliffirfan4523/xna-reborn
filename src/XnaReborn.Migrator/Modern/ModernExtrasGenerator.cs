using System.Text;
using XnaReborn.Migrator.Output;

namespace XnaReborn.Migrator.Modern;

/// <summary>
/// Writes <c>XnaReborn.Modern.cs</c>, the small helper that adds the opt-in window extras to a migrated game: a resizable window,
/// an Alt+Enter fullscreen toggle and high-DPI awareness. The game keeps its own resolution as the back buffer and the helper
/// scales the finished frame, so no gameplay code changes. Pure: returns text and never touches disk.
/// </summary>
public static class ModernExtrasGenerator
{
    /// <summary>File name of the helper, written into the folder of each game project that gets the hook.</summary>
    public const string FileName = "XnaReborn.Modern.cs";

    /// <summary>Namespace of the helper.</summary>
    public const string Namespace = "XnaReborn.Modern";

    /// <summary>The call that the hook adds before <c>game.Run()</c>, without its argument.</summary>
    public const string AttachCall = Namespace + ".ModernExtras.Attach";

    private const string _reason = "Modern extras: opt-in helper for window resize, fullscreen and high-DPI. See the manifest for its limits.";

    /// <summary>Creates the helper file for one game project.</summary>
    /// <param name="projectDirectory">Folder of the game project relative to the output root, with '/' separators. Empty for the root.</param>
    /// <param name="choice">The extras that are on. Must have at least one.</param>
    /// <returns>A <see cref="ChangeKind.Created"/> change with LF line endings.</returns>
    /// <exception cref="ArgumentException">No extra is on.</exception>
    public static FileChange Generate(string projectDirectory, ModernExtrasChoice choice)
    {
        ArgumentNullException.ThrowIfNull(projectDirectory);
        ArgumentNullException.ThrowIfNull(choice);
        if (!choice.Any)
        {
            throw new ArgumentException("At least one extra must be on.", nameof(choice));
        }

        var path = projectDirectory.Length == 0 ? FileName : projectDirectory + "/" + FileName;
        return new FileChange(path, ChangeKind.Created, null, Source(choice), _reason);
    }

    /// <summary>Plain statements of what the chosen extras do not do, for the manifest.</summary>
    /// <param name="choice">The extras that are on.</param>
    /// <returns>One line per limit, in a fixed order.</returns>
    public static IReadOnlyList<string> Limits(ModernExtrasChoice choice)
    {
        ArgumentNullException.ThrowIfNull(choice);
        var limits = new List<string>();
        if (choice.NeedsScaling)
        {
            limits.Add("The game is drawn at its own resolution and scaled to the window with black bars. Mouse and touch positions are not remapped, so they only line up while the window has the game's own size.");
            limits.Add("The game's resolution is read from the first frame. A game that changes its own resolution later keeps drawing at the first size.");
            limits.Add("A game that draws to its own render target and does not restore the one the helper bound shows that frame unscaled.");
        }

        if (choice.HighDpi)
        {
            limits.Add("High-DPI is Windows only. Windows no longer enlarges the window, so it looks smaller on a high-DPI screen; use window resize or fullscreen with it.");
        }

        limits.Add("XNA Reborn has only checked that the helper compiles. Run the game to see how the window looks and behaves.");
        return limits;
    }

    private static string Source(ModernExtrasChoice choice)
    {
        var sb = new StringBuilder();
        sb.Append("// Generated by XNA Reborn. Opt-in window extras: ").Append(string.Join(", ", choice.FeatureNames())).Append(".\n");
        sb.Append("// The game keeps its own resolution as the back buffer. This file never touches gameplay code.\n");
        sb.Append("using System;\n");
        if (choice.HighDpi)
        {
            sb.Append("using System.Runtime.CompilerServices;\n");
            sb.Append("using System.Runtime.InteropServices;\n");
        }

        sb.Append("using Microsoft.Xna.Framework;\n");
        if (choice.NeedsScaling)
        {
            sb.Append("using Microsoft.Xna.Framework.Graphics;\n");
            sb.Append("using Microsoft.Xna.Framework.Input;\n");
        }

        sb.Append("\nnamespace ").Append(Namespace).Append('\n').Append("{\n");
        sb.Append("    internal static class ModernExtras\n    {\n");
        sb.Append("        /// <summary>Call once after the game is created and before it runs.</summary>\n");
        sb.Append("        internal static void Attach(Game game)\n        {\n");
        sb.Append("            if (game == null)\n            {\n                throw new ArgumentNullException(nameof(game));\n            }\n");
        if (choice.AllowWindowResize)
        {
            sb.Append("\n            game.Window.AllowUserResizing = true;\n");
        }

        if (choice.NeedsScaling)
        {
            sb.Append("\n            game.Components.Add(new ScaledPresenter(game, ")
                .Append(choice.FullscreenToggle ? "true" : "false").Append("));\n");
        }

        sb.Append("        }\n    }\n");
        if (choice.HighDpi)
        {
            sb.Append(_highDpiSource);
        }

        if (choice.NeedsScaling)
        {
            sb.Append(_scaledPresenterSource);
        }

        sb.Append("}\n");
        return sb.ToString();
    }

    private const string _highDpiSource = """

            internal static class HighDpi
            {
                // Runs before Main, so before any window exists. Windows only; later calls and other systems do nothing.
                [ModuleInitializer]
                internal static void Enable()
                {
                    if (!OperatingSystem.IsWindows())
                    {
                        return;
                    }

                    try
                    {
                        SetProcessDpiAwarenessContext(new IntPtr(-4)); // per-monitor v2
                    }
                    catch (DllNotFoundException)
                    {
                    }
                    catch (EntryPointNotFoundException)
                    {
                    }
                }

                [DllImport("user32.dll")]
                private static extern bool SetProcessDpiAwarenessContext(IntPtr value);
            }

        """;

    private const string _scaledPresenterSource = """

            // Binds an off-screen target of the game's own size at the end of Update, so the game draws as usual, then scales it to the
            // back buffer at the end of Draw. If the game binds its own target and never restores ours, that frame is left unscaled.
            internal sealed class ScaledPresenter : DrawableGameComponent
            {
                private readonly bool _fullscreenToggle;
                private RenderTarget2D _target;
                private SpriteBatch _batch;
                private int _width;
                private int _height;
                private bool _toggleHeld;

                internal ScaledPresenter(Game game, bool fullscreenToggle)
                    : base(game)
                {
                    _fullscreenToggle = fullscreenToggle;
                    UpdateOrder = int.MaxValue;
                    DrawOrder = int.MaxValue;
                }

                public override void Update(GameTime gameTime)
                {
                    if (_fullscreenToggle)
                    {
                        PollToggle();
                    }

                    if (_target == null)
                    {
                        // The first frame: the game has set its resolution by now. This size stays for the whole run.
                        var pp = GraphicsDevice.PresentationParameters;
                        _width = pp.BackBufferWidth;
                        _height = pp.BackBufferHeight;
                        _target = new RenderTarget2D(GraphicsDevice, _width, _height, false, SurfaceFormat.Color, DepthFormat.Depth24Stencil8, 0, RenderTargetUsage.PreserveContents);
                        _batch = new SpriteBatch(GraphicsDevice);
                    }

                    GraphicsDevice.SetRenderTarget(_target);
                    base.Update(gameTime);
                }

                public override void Draw(GameTime gameTime)
                {
                    var bound = GraphicsDevice.GetRenderTargets();
                    if (_target != null && bound.Length == 1 && ReferenceEquals(bound[0].RenderTarget, _target))
                    {
                        GraphicsDevice.SetRenderTarget(null);
                        var pp = GraphicsDevice.PresentationParameters;
                        var scale = Math.Min((float)pp.BackBufferWidth / _width, (float)pp.BackBufferHeight / _height);
                        var width = Math.Max(1, (int)(_width * scale));
                        var height = Math.Max(1, (int)(_height * scale));
                        var area = new Rectangle((pp.BackBufferWidth - width) / 2, (pp.BackBufferHeight - height) / 2, width, height);
                        GraphicsDevice.Viewport = new Viewport(0, 0, pp.BackBufferWidth, pp.BackBufferHeight);
                        GraphicsDevice.Clear(Color.Black);
                        _batch.Begin(samplerState: SamplerState.LinearClamp);
                        _batch.Draw(_target, area, Color.White);
                        _batch.End();
                    }

                    base.Draw(gameTime);
                }

                protected override void Dispose(bool disposing)
                {
                    if (disposing)
                    {
                        _target?.Dispose();
                        _batch?.Dispose();
                    }

                    base.Dispose(disposing);
                }

                private void PollToggle()
                {
                    var keys = Keyboard.GetState();
                    var down = (keys.IsKeyDown(Keys.LeftAlt) || keys.IsKeyDown(Keys.RightAlt)) && keys.IsKeyDown(Keys.Enter);
                    if (down && !_toggleHeld && Game.Services.GetService(typeof(IGraphicsDeviceManager)) is GraphicsDeviceManager manager)
                    {
                        manager.HardwareModeSwitch = false; // borderless: keeps the desktop mode
                        manager.ToggleFullScreen();
                    }

                    _toggleHeld = down;
                }
            }

        """;
}
