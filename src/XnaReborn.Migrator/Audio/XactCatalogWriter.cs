using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using XnaReborn.Core.Models.Xact;
using XnaReborn.Migrator.Source;

namespace XnaReborn.Migrator.Audio;

/// <summary>The generated catalog source and the findings from writing it.</summary>
/// <param name="Text">The C# source of <c>XactCatalog.g.cs</c>.</param>
/// <param name="Findings">Conflicts between projects that use the same file stem.</param>
public sealed record XactCatalogResult(string Text, IReadOnlyList<RewriteNote> Findings);

/// <summary>
/// Writes <c>XnaReborn.Compat/XactCatalog.g.cs</c>: the contents of the .xap files as static data, with units already converted
/// (hundredths of a decibel to a gain, hundredths of a semitone to the XNA pitch range). The output is deterministic: file order,
/// invariant culture, round-trip float text.
/// </summary>
/// <remarks>
/// The generated code calls constructors of data types (<c>XactEngineData</c>, <c>XactWaveBankData</c>, ...) that the shim
/// defines in the same namespace. Their signatures are the contract between this writer and the shim; see <see cref="XactCatalogContract"/>.
/// </remarks>
public static partial class XactCatalogWriter
{
    /// <summary>Rule id of the note for a stem that two .xap files both use.</summary>
    public const string ConflictRuleId = "XNA016";

    [GeneratedRegex(@"Sound\[(?<n>[^\]]+)\]", RegexOptions.CultureInvariant)]
    private static partial Regex SoundInPath();

    /// <summary>Writes the catalog for every project. Projects are written in the given order; a stem that is used twice keeps its first owner.</summary>
    /// <param name="projects">The projects, each with its plan.</param>
    /// <param name="contentRoot">The content folder the game uses, such as <c>Content</c>.</param>
    public static XactCatalogResult Write(IReadOnlyList<(XapProject Project, XactPlan Plan)> projects, string contentRoot)
    {
        ArgumentNullException.ThrowIfNull(projects);
        ArgumentNullException.ThrowIfNull(contentRoot);
        var findings = new List<RewriteNote>();
        var engines = new List<string>();
        var waveBanks = new List<string>();
        var soundBanks = new List<string>();
        var engineStems = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var waveStems = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var soundStems = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var (project, plan) in projects)
        {
            if (!engineStems.Add(plan.EngineStem))
            {
                findings.Add(new RewriteNote(ConflictRuleId, $"{project.Path}: the engine file name '{plan.EngineStem}' is already used by another .xap, so this one was left out of the catalog.", true));
                continue;
            }

            engines.Add(Engine(project, plan));
            foreach (var bank in project.WaveBanks)
            {
                var stem = bank.FileStem ?? bank.Name;
                if (waveStems.Add(stem))
                {
                    waveBanks.Add(WaveBank(bank, stem, plan));
                }
                else
                {
                    findings.Add(new RewriteNote(ConflictRuleId, $"{project.Path}: the wave bank file name '{stem}' is already used, so bank '{bank.Name}' was left out of the catalog.", true));
                }
            }

            foreach (var bank in project.SoundBanks)
            {
                var stem = bank.FileStem ?? bank.Name;
                if (soundStems.Add(stem))
                {
                    soundBanks.Add(SoundBank(bank, stem, project));
                }
                else
                {
                    findings.Add(new RewriteNote(ConflictRuleId, $"{project.Path}: the sound bank file name '{stem}' is already used, so bank '{bank.Name}' was left out of the catalog.", true));
                }
            }
        }

        var sb = new StringBuilder();
        sb.Append("// Generated by XNA Reborn. Do not edit.\n");
        sb.Append("namespace XnaReborn.Compat.Xact\n{\n");
        sb.Append("    internal static partial class XactCatalog\n    {\n");
        sb.Append("        internal const string ContentRoot = ").Append(Str(contentRoot)).Append(";\n\n");
        Array(sb, "XactEngineData", "Engines", engines);
        Array(sb, "XactWaveBankData", "WaveBanks", waveBanks);
        Array(sb, "XactSoundBankData", "SoundBanks", soundBanks);
        sb.Length -= 1; // drop the blank line after the last array
        sb.Append("    }\n}\n");
        return new XactCatalogResult(sb.ToString(), findings);
    }

    /// <summary>Converts hundredths of a decibel to a linear gain: 0 is 1.0, -1200 is about 0.251.</summary>
    /// <param name="centiDb">Volume in hundredths of a decibel.</param>
    public static float Gain(int centiDb) => (float)Math.Pow(10, centiDb / 2000.0);

    /// <summary>Converts hundredths of a semitone to the XNA pitch range, -1 to 1 (an octave up or down).</summary>
    /// <param name="cents">Pitch in hundredths of a semitone.</param>
    public static float Pitch(int cents) => Math.Clamp(cents / 1200f, -1f, 1f);

    private static void Array(StringBuilder sb, string type, string name, List<string> items)
    {
        if (items.Count == 0)
        {
            sb.Append($"        internal static readonly {type}[] {name} = new {type}[0];\n\n");
            return;
        }

        sb.Append($"        internal static readonly {type}[] {name} =\n        {{\n");
        foreach (var item in items)
        {
            sb.Append("            ").Append(item).Append(",\n");
        }

        sb.Append("        };\n\n");
    }

    private static string Engine(XapProject project, XactPlan plan) =>
        $"new XactEngineData({Str(plan.EngineStem)}, "
        + List("XactCategoryData", project.Categories.Select(c =>
            $"new XactCategoryData({Str(c.Name)}, {Float(Gain(c.VolumeCentiDb))}, {Bool(c.IsPublic)}, {Bool(c.BackgroundMusic)}, {c.MaxInstances}, {c.Behavior}, {c.FadeInMs}, {c.FadeOutMs}, {Strings(c.Parents)})"))
        + ", "
        + List("XactVariableData", project.Variables.Select(v =>
            $"new XactVariableData({Str(v.Name)}, {Bool(v.IsGlobal)}, {Bool(v.IsPublic)}, {Bool(v.ReadOnly)}, {Float(v.InitialValue)}, {Float(v.Min)}, {Float(v.Max)})"))
        + ", "
        + List("XactRpcData", project.Rpcs.Select(r =>
            $"new XactRpcData({Str(r.Name)}, " + List("XactRpcCurveData", r.Curves.Select(c =>
                $"new XactRpcCurveData({Str(c.Name)}, {c.Property}, {Bool(c.IsSound)}, {Str(c.VariableName)}, "
                + List("XactRpcPointData", c.Points.Select(p => $"new XactRpcPointData({Float(p.X)}, {Float(p.Y)}, {p.CurveShape})")) + ")")) + ")"))
        + ")";

    private static string WaveBank(XapWaveBank bank, string stem, XactPlan plan) =>
        $"new XactWaveBankData({Str(stem)}, {Str(bank.Name)}, {Bool(bank.Streaming)}, "
        + List("XactWaveData", bank.Waves.Select(w =>
        {
            var asset = plan.Assets.FirstOrDefault(a => a.AssetName == plan.AssetByWave.GetValueOrDefault(bank.Name + "|" + w.Name));
            var kind = asset?.Kind ?? XactWaveKind.SoundEffect;
            return $"new XactWaveData({Str(w.Name)}, {Str(asset?.AssetName ?? string.Empty)}, XactWaveKind.{kind}, {Bool(asset is null || !asset.Exists)}, {Bool(w.LoopRegionLength > 0)})";
        })) + ")";

    private static string SoundBank(XapSoundBank bank, string stem, XapProject project)
    {
        var bySound = UnsupportedBySound(project);
        return $"new XactSoundBankData({Str(stem)}, {Str(bank.Name)}, "
            + List("XactSoundData", bank.Sounds.Select(s =>
                $"new XactSoundData({Str(s.Name)}, {Float(Gain(s.VolumeCentiDb))}, {Float(Pitch(s.PitchCents))}, {s.Priority}, {Strings(s.Categories)}, {Strings(s.RpcNames)}, "
                + List("XactTrackData", s.Tracks.Select(t =>
                    $"new XactTrackData({Float(Gain(t.VolumeCentiDb))}, "
                    + List("XactEventData", t.Events.Select(e =>
                        $"new XactEventData({e.LoopCount}, {e.TimestampMs}, {Bool(e.Relative)}, "
                        + List("XactWaveEntryData", e.Entries.Select(w => $"new XactWaveEntryData({Str(w.BankName)}, {Str(w.EntryName)}, {w.Weight})")) + ")"))
                    + ")")) + ")"))
            + ", "
            + List("XactCueData", bank.Cues.Select(c =>
            {
                var notes = c.Entries.SelectMany(e => bySound.GetValueOrDefault(e.SoundName) ?? []).Distinct(StringComparer.Ordinal).ToList();
                return $"new XactCueData({Str(c.Name)}, {c.VariationType}, {Bool(c.NewVariationOnLoop)}, "
                    + List("XactCueEntryData", c.Entries.Select(e => $"new XactCueEntryData({Str(e.SoundName)}, {e.WeightMin}, {e.WeightMax})"))
                    + $", {Strings(notes)})";
            }))
            + ")";
    }

    /// <summary>Groups the unsupported items of a project that belong to a sound (their path has <c>Sound[name]</c>) by sound name. Each entry reads <c>feature (line N)</c>.</summary>
    /// <param name="project">The parsed project.</param>
    /// <returns>Sound name to the unsupported items, in file order.</returns>
    public static IReadOnlyDictionary<string, List<string>> UnsupportedBySound(XapProject project)
    {
        ArgumentNullException.ThrowIfNull(project);
        return project.Unsupported
            .Select(u => (Item: u, Match: SoundInPath().Match(u.Path)))
            .Where(x => x.Match.Success)
            .GroupBy(x => x.Match.Groups["n"].Value, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.Select(x => x.Item.Path[(x.Item.Path.LastIndexOf('/') + 1)..] + " (line " + x.Item.Line.ToString(CultureInfo.InvariantCulture) + ")").ToList(), StringComparer.Ordinal);
    }

    private static string List(string type, IEnumerable<string> items)
    {
        var list = items.ToList();
        return list.Count == 0 ? $"new {type}[0]" : $"new {type}[] {{ " + string.Join(", ", list) + " }";
    }

    private static string Strings(IEnumerable<string> values)
    {
        var list = values.ToList();
        return list.Count == 0 ? "new string[0]" : "new string[] { " + string.Join(", ", list.Select(Str)) + " }";
    }

    private static string Bool(bool value) => value ? "true" : "false";

    private static string Float(float value) =>
        value.ToString("R", CultureInfo.InvariantCulture) + "f";

    private static string Str(string value)
    {
        var sb = new StringBuilder("\"");
        foreach (var c in value)
        {
            sb.Append(c switch
            {
                '\\' => "\\\\",
                '"' => "\\\"",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                _ when char.IsControl(c) => "\\u" + ((int)c).ToString("x4", CultureInfo.InvariantCulture),
                _ => c.ToString(),
            });
        }

        return sb.Append('"').ToString();
    }
}

/// <summary>
