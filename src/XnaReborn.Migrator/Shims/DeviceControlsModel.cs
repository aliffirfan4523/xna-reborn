using System.Globalization;
using System.Text;

namespace XnaReborn.Migrator.Shims;

/// <summary>One action of the device stand-ins and the keyboard keys that trigger it.</summary>
/// <param name="Name">C# identifier of the action in the generated <c>DeviceControls</c> class, such as MoveLeft.</param>
/// <param name="Description">What the action does, for the controls file.</param>
/// <param name="Keys">Names of MonoGame <c>Keys</c> members.</param>
public sealed record KeyBinding(string Name, string Description, IReadOnlyList<string> Keys);

/// <summary>
/// The one table of keys and tilt numbers behind the device stand-ins. The generated <c>DeviceControls.cs</c> and
/// <c>DEVICE-CONTROLS.md</c> are both written from it, so the file and the code cannot drift apart.
/// </summary>
/// <param name="TiltFull">Tilt, in g, on the X and Y axes when a direction key is held.</param>
/// <param name="EaseSeconds">Time constant of the easing between the resting reading and a tilt.</param>
/// <param name="UpdateMilliseconds">Default time between accelerometer readings.</param>
/// <param name="UseMouseTilt">When true the tilt follows the mouse offset from the window centre instead of the keys.</param>
/// <param name="OpenWebLinks">When true a web browser task opens http and https links in the default browser.</param>
/// <param name="Bindings">The keyboard bindings, in a fixed order.</param>
public sealed record DeviceControlsModel(
    float TiltFull,
    float EaseSeconds,
    float UpdateMilliseconds,
    bool UseMouseTilt,
    bool OpenWebLinks,
    IReadOnlyList<KeyBinding> Bindings)
{
    /// <summary>The device lying face up: gravity along the negative Z axis, in g.</summary>
    public static readonly float RestingX = 0f;

    /// <summary>See <see cref="RestingX"/>.</summary>
    public static readonly float RestingY = 0f;

    /// <summary>See <see cref="RestingX"/>.</summary>
    public static readonly float RestingZ = -1f;

    /// <summary>Gets the shipped values.</summary>
    public static DeviceControlsModel Default { get; } = new(
        0.7f,
        0.12f,
        20f,
        false,
        false,
        [
            new("MoveLeft", "Left stick and D-pad left, tilt left", ["Left", "A"]),
            new("MoveRight", "Left stick and D-pad right, tilt right", ["Right", "D"]),
            new("MoveUp", "Left stick and D-pad up, tilt up (top edge down)", ["Up", "W"]),
            new("MoveDown", "Left stick and D-pad down, tilt down (top edge up)", ["Down", "S"]),
            new("ButtonA", "A button", ["Space", "Enter"]),
            new("ButtonB", "B button", ["Z"]),
            new("ButtonX", "X button", ["X"]),
            new("ButtonY", "Y button", ["C"]),
            new("Back", "Back button (the phone's hardware Back button)", ["Escape"]),
            new("Start", "Start button", ["Tab"]),
            new("LeftShoulder", "Left shoulder button", ["Q"]),
            new("RightShoulder", "Right shoulder button", ["E"]),
        ]);

    /// <summary>Formats a number the way C# source and the controls file write it.</summary>
    /// <param name="value">The number.</param>
    internal static string Number(float value) => value.ToString("0.0###", CultureInfo.InvariantCulture);

    /// <summary>Writes the generated <c>DeviceControls.cs</c>.</summary>
    internal string ToCSharp()
    {
        var sb = new StringBuilder()
            .Append("// Generated by XNA Reborn. The single table of keys and tilt numbers for the device stand-ins.\n")
            .Append("// Change a value here and rebuild; DEVICE-CONTROLS.md in the output folder lists the values it was written with.\n")
            .Append("using Microsoft.Xna.Framework.Input;\n\n")
            .Append("namespace XnaReborn.Compat.Device\n{\n")
            .Append("    public static class DeviceControls\n    {\n")
            .Append("        /// <summary>Tilt in g on X and Y while a direction key is held.</summary>\n")
            .Append("        public static readonly float TiltFull = ").Append(Number(TiltFull)).Append("f;\n\n")
            .Append("        /// <summary>Time constant, in seconds, of the easing between readings.</summary>\n")
            .Append("        public static readonly float EaseSeconds = ").Append(Number(EaseSeconds)).Append("f;\n\n")
            .Append("        /// <summary>Resting reading: the device lying face up.</summary>\n")
            .Append("        public static readonly float RestingX = ").Append(Number(RestingX)).Append("f;\n")
            .Append("        public static readonly float RestingY = ").Append(Number(RestingY)).Append("f;\n")
            .Append("        public static readonly float RestingZ = ").Append(Number(RestingZ)).Append("f;\n\n")
            .Append("        /// <summary>Default time between accelerometer readings.</summary>\n")
            .Append("        public static readonly double UpdateMilliseconds = ").Append(Number(UpdateMilliseconds)).Append(";\n\n")
            .Append("        /// <summary>True to tilt with the mouse offset from the window centre instead of the keys.</summary>\n")
            .Append("        public static readonly bool UseMouseTilt = ").Append(UseMouseTilt ? "true" : "false").Append(";\n\n")
            .Append("        /// <summary>True to let a web browser task open http and https links.</summary>\n")
            .Append("        public static readonly bool OpenWebLinks = ").Append(OpenWebLinks ? "true" : "false").Append(";\n");
        foreach (var binding in Bindings)
        {
            sb.Append("\n        /// <summary>").Append(binding.Description).Append(".</summary>\n")
                .Append("        public static readonly Keys[] ").Append(binding.Name).Append(" = { ")
                .Append(string.Join(", ", binding.Keys.Select(k => "Keys." + k))).Append(" };\n");
        }

        return sb.Append("    }\n}\n").ToString();
    }

    /// <summary>Writes <c>DEVICE-CONTROLS.md</c>.</summary>
    internal string ToMarkdown()
    {
        var sb = new StringBuilder()
            .Append("# Device controls\n\n")
            .Append("This game was built for a phone, a Zune or an Xbox 360. On a desktop the device input is stood in for by the keyboard and the mouse.\n")
            .Append("The numbers below come from `XnaReborn.Compat/Device/DeviceControls.cs`. Change them there.\n\n")
            .Append("## Keyboard\n\n")
            .Append("| Action | Keys |\n|---|---|\n");
        foreach (var binding in Bindings)
        {
            sb.Append("| ").Append(binding.Description).Append(" | ").Append(string.Join(", ", binding.Keys)).Append(" |\n");
        }

        sb.Append("\nA connected game pad is used as it is. Escape is also reported as the Back button while a pad is connected.\n")
            .Append("Only player one has the keyboard. Players two to four use their own pads.\n\n")
            .Append("## Mouse and touch\n\n")
            .Append("- The mouse cursor is visible.\n")
            .Append("- Hold the left mouse button to touch the screen. A press is a Tap, a drag is FreeDrag, and releasing it is DragComplete.\n")
            .Append("- Only one touch point is possible, so pinch and other two-finger gestures are not available.\n\n")
            .Append("## Tilt (accelerometer)\n\n")
            .Append("| Setting | Value |\n|---|---|\n")
            .Append("| Source | ").Append(UseMouseTilt ? "mouse offset from the window centre" : "the move keys above").Append(" |\n")
            .Append("| Resting reading (device lying face up) | (").Append(Number(RestingX)).Append(", ").Append(Number(RestingY)).Append(", ").Append(Number(RestingZ)).Append(") g |\n")
            .Append("| Full tilt on X and Y | ").Append(Number(TiltFull)).Append(" g |\n")
            .Append("| Easing time constant | ").Append(Number(EaseSeconds)).Append(" s |\n")
            .Append("| Time between readings | ").Append(Number(UpdateMilliseconds)).Append(" ms |\n\n")
            .Append("Readings are raised from the game loop, never from another thread. Axes follow the Windows Phone sensor: X to the right, Y toward the top of the screen, Z out of the screen.\n\n")
            .Append("## Window\n\n")
            .Append("- The game starts in a window, even when its code asks for full screen.\n")
            .Append("- The back buffer keeps the size the game asked for. When it is taller than the display, the window can be resized.\n\n")
            .Append("## Not available on a desktop\n\n")
            .Append("- Phone choosers (photo, camera, ringtone): they throw `NotSupportedException`.\n")
            .Append("- The device media library, phone launchers (they only write a log line), and the marketplace (the game always counts as the full version).\n")
            .Append("- Multi-touch, vibration and the phone shell events (`Activated`, `Deactivated` and the like never fire).\n")
            .Append("- Web links: ").Append(OpenWebLinks ? "opened in the default browser" : "not opened. Set `OpenWebLinks` in DeviceControls.cs to allow it").Append(".\n");
        return sb.ToString();
    }
}
