    /// <summary>The Windows Phone accelerometer (Microsoft.Devices.Sensors), driven by the keyboard or the mouse.</summary>
    internal const string Accelerometer = """
        // Generated by XNA Reborn. Stand-in for the Windows Phone accelerometer (rule XNA060).
        // Readings come from the tilt source in DeviceControls.cs and are raised from the game loop (DeviceInput.Update).
        using System;
        using System.Collections.Generic;
        using Microsoft.Xna.Framework;
        using XnaReborn.Compat.Device;

        namespace Microsoft.Devices.Sensors
        {
            /// <summary>State of a sensor.</summary>
            public enum SensorState
            {
                NotSupported,
                Initializing,
                Ready,
                NoData,
                Disabled,
            }

            /// <summary>One accelerometer reading, in g.</summary>
            public readonly struct AccelerometerReading
            {
                public AccelerometerReading(Vector3 acceleration, DateTimeOffset timestamp)
                {
                    Acceleration = acceleration;
                    Timestamp = timestamp;
                }

                public Vector3 Acceleration { get; }

                public DateTimeOffset Timestamp { get; }
            }

            /// <summary>The data of <see cref="Accelerometer.ReadingChanged"/>.</summary>
            public sealed class AccelerometerReadingEventArgs : EventArgs
            {
                public AccelerometerReadingEventArgs(double x, double y, double z, DateTimeOffset timestamp)
                {
                    X = x;
                    Y = y;
                    Z = z;
                    Timestamp = timestamp;
                }

                public double X { get; }

                public double Y { get; }

                public double Z { get; }

                public DateTimeOffset Timestamp { get; }
            }

            /// <summary>Stand-in for the phone accelerometer. Start throws when the DeviceInput component is not installed.</summary>
            public sealed class Accelerometer : IDisposable
            {
                private static readonly List<WeakReference<Accelerometer>> _started = new List<WeakReference<Accelerometer>>();

                private TimeSpan _sinceLastReading;

                public static bool IsSupported => true;

                public SensorState State { get; private set; } = SensorState.Disabled;

                public AccelerometerReading CurrentValue { get; private set; }

                public TimeSpan TimeBetweenUpdates { get; set; } = TimeSpan.FromMilliseconds(DeviceControls.UpdateMilliseconds);

                public event EventHandler<AccelerometerReadingEventArgs>? ReadingChanged;

                public void Start()
                {
                    if (!DeviceRuntime.InputInstalled)
                    {
                        throw new InvalidOperationException(
                            "XNA060: the accelerometer stand-in is driven by the XnaReborn.Compat.Input.DeviceInput game component, which is not installed. See DEVICE-CONTROLS.md.");
                    }

                    if (State == SensorState.Ready)
                    {
                        return;
                    }

                    State = SensorState.Ready;
                    _sinceLastReading = TimeSpan.Zero;
                    lock (_started)
                    {
                        _started.Add(new WeakReference<Accelerometer>(this));
                    }
                }

                public void Stop()
                {
                    State = SensorState.Disabled;
                    lock (_started)
                    {
                        _started.RemoveAll(w => !w.TryGetTarget(out var other) || ReferenceEquals(other, this));
                    }
                }

                public void Dispose() => Stop();

                /// <summary>Called by DeviceInput once per frame, on the game thread.</summary>
                internal static void TickAll(TimeSpan elapsed)
                {
                    var running = new List<Accelerometer>();
                    lock (_started)
                    {
                        _started.RemoveAll(w => !w.TryGetTarget(out _));
                        foreach (var weak in _started)
                        {
                            if (weak.TryGetTarget(out var sensor))
                            {
                                running.Add(sensor);
                            }
                        }
                    }

                    foreach (var sensor in running)
                    {
                        sensor.Tick(elapsed);
                    }
                }

                private void Tick(TimeSpan elapsed)
                {
                    if (State != SensorState.Ready)
                    {
                        return;
                    }

                    _sinceLastReading += elapsed;
                    if (_sinceLastReading < TimeBetweenUpdates)
                    {
                        return;
                    }

                    _sinceLastReading = TimeSpan.Zero;
                    var now = DateTimeOffset.UtcNow;
                    var tilt = DeviceRuntime.Tilt;
                    CurrentValue = new AccelerometerReading(tilt, now);
                    ReadingChanged?.Invoke(this, new AccelerometerReadingEventArgs(tilt.X, tilt.Y, tilt.Z, now));
                }
            }
        }
        """;

    /// <summary>The pure tilt maths.</summary>
    internal const string TiltMapper = """
        // Generated by XNA Reborn. Pure tilt maths: held keys or a mouse offset in, an accelerometer reading out.
        using System;
        using Microsoft.Xna.Framework;

        namespace XnaReborn.Compat.Device
        {
            /// <summary>The tilt input of one frame. MouseOffset is the mouse position from the window centre, each axis from -1 to 1.</summary>
            internal readonly record struct TiltInput(bool Left, bool Right, bool Up, bool Down, Vector2? MouseOffset);

            internal static class TiltMapper
            {
                internal static Vector3 Resting => new Vector3(DeviceControls.RestingX, DeviceControls.RestingY, DeviceControls.RestingZ);

                /// <summary>The reading the device would show for this input. X to the right, Y to the top of the screen, Z out of the screen, in g.</summary>
                internal static Vector3 Target(TiltInput input)
                {
                    float x;
                    float y;
                    if (input.MouseOffset is Vector2 offset)
                    {
                        x = Math.Clamp(offset.X, -1f, 1f) * DeviceControls.TiltFull;
                        y = -Math.Clamp(offset.Y, -1f, 1f) * DeviceControls.TiltFull;
                    }
                    else
                    {
                        x = ((input.Right ? 1f : 0f) - (input.Left ? 1f : 0f)) * DeviceControls.TiltFull;
                        y = ((input.Up ? 1f : 0f) - (input.Down ? 1f : 0f)) * DeviceControls.TiltFull;
                    }

                    if (x == 0f && y == 0f)
                    {
                        return Resting;
                    }

                    // Keep the vector near 1 g: gravity that does not point along X or Y points into the screen.
                    return new Vector3(x, y, -MathF.Sqrt(MathF.Max(0f, 1f - (x * x) - (y * y))));
                }

                /// <summary>Moves a reading toward a target. After one time constant it has covered about 63 percent of the way.</summary>
                internal static Vector3 Ease(Vector3 current, Vector3 target, float seconds)
                {
                    if (seconds <= 0f)
                    {
                        return current;
                    }

                    if (DeviceControls.EaseSeconds <= 0f)
                    {
                        return target;
                    }

                    var amount = 1f - MathF.Exp(-seconds / DeviceControls.EaseSeconds);
                    return Vector3.Lerp(current, target, amount);
                }
            }
        }
        """;

