    /// <summary>The pure game pad mapping.</summary>
    internal const string GamePadMapper = """
        // Generated by XNA Reborn. Pure game pad mapping: a keyboard state in, a game pad state out.
        using System;
        using System.Collections.Generic;
        using Microsoft.Xna.Framework;
        using Microsoft.Xna.Framework.Input;
        using XnaReborn.Compat.Device;

        namespace XnaReborn.Compat.Input
        {
            internal static class GamePadMapper
            {
                /// <summary>A connected pad built from the keys in DeviceControls.cs. The left stick and the D-pad follow the move keys.</summary>
                internal static GamePadState FromKeyboard(KeyboardState keys)
                {
                    var left = IsDown(keys, DeviceControls.MoveLeft);
                    var right = IsDown(keys, DeviceControls.MoveRight);
                    var up = IsDown(keys, DeviceControls.MoveUp);
                    var down = IsDown(keys, DeviceControls.MoveDown);
                    var buttons = new List<Buttons>();
                    Add(buttons, left, Buttons.DPadLeft);
                    Add(buttons, right, Buttons.DPadRight);
                    Add(buttons, up, Buttons.DPadUp);
                    Add(buttons, down, Buttons.DPadDown);
                    Add(buttons, IsDown(keys, DeviceControls.ButtonA), Buttons.A);
                    Add(buttons, IsDown(keys, DeviceControls.ButtonB), Buttons.B);
                    Add(buttons, IsDown(keys, DeviceControls.ButtonX), Buttons.X);
                    Add(buttons, IsDown(keys, DeviceControls.ButtonY), Buttons.Y);
                    Add(buttons, IsDown(keys, DeviceControls.Back), Buttons.Back);
                    Add(buttons, IsDown(keys, DeviceControls.Start), Buttons.Start);
                    Add(buttons, IsDown(keys, DeviceControls.LeftShoulder), Buttons.LeftShoulder);
                    Add(buttons, IsDown(keys, DeviceControls.RightShoulder), Buttons.RightShoulder);
                    var stick = new Vector2((right ? 1f : 0f) - (left ? 1f : 0f), (up ? 1f : 0f) - (down ? 1f : 0f));
                    return new GamePadState(stick, Vector2.Zero, 0f, 0f, buttons.ToArray());
                }

                /// <summary>A connected pad is returned as it is, except that the Back key also presses Back. Without a pad the keyboard is the pad.</summary>
                internal static GamePadState Combine(GamePadState pad, KeyboardState keys)
                {
                    if (!pad.IsConnected)
                    {
                        return FromKeyboard(keys);
                    }

                    if (!IsDown(keys, DeviceControls.Back) || pad.IsButtonDown(Buttons.Back))
                    {
                        return pad;
                    }

                    var buttons = new List<Buttons> { Buttons.Back };
                    foreach (var button in Enum.GetValues<Buttons>())
                    {
                        if (pad.IsButtonDown(button))
                        {
                            buttons.Add(button);
                        }
                    }

                    return new GamePadState(pad.ThumbSticks.Left, pad.ThumbSticks.Right, pad.Triggers.Left, pad.Triggers.Right, buttons.ToArray());
                }

                private static bool IsDown(KeyboardState keys, Keys[] any)
                {
                    foreach (var key in any)
                    {
                        if (keys.IsKeyDown(key))
                        {
                            return true;
                        }
                    }

                    return false;
                }

                private static void Add(List<Buttons> buttons, bool pressed, Buttons button)
                {
                    if (pressed)
                    {
                        buttons.Add(button);
                    }
                }
            }
        }
        """;

    /// <summary>The replacement for GamePad.GetState.</summary>
    internal const string CompatGamePad = """
        // Generated by XNA Reborn. Replacement for GamePad.GetState on a desktop (rule XNA062).
        // Player one gets the real pad when one is connected and the keyboard otherwise. Escape always counts as Back.
        // GetCapabilities and SetVibration are not redirected: MonoGame supports them.
        using Microsoft.Xna.Framework;
        using Microsoft.Xna.Framework.Input;

        namespace XnaReborn.Compat.Input
        {
            public static class CompatGamePad
            {
                public static GamePadState GetState(PlayerIndex playerIndex) =>
                    Map(playerIndex, GamePad.GetState(playerIndex));

                public static GamePadState GetState(PlayerIndex playerIndex, GamePadDeadZone deadZone) =>
                    Map(playerIndex, GamePad.GetState(playerIndex, deadZone));

                private static GamePadState Map(PlayerIndex playerIndex, GamePadState pad) =>
                    playerIndex == PlayerIndex.One ? GamePadMapper.Combine(pad, Keyboard.GetState()) : pad;
            }
        }
        """;

    /// <summary>The game component that sets the desktop up for a device game.</summary>
    internal const string DeviceInput = """
        // Generated by XNA Reborn. Game component that sets a device game up on a desktop (rules XNA060, XNA061, XNA062).
        // It turns on the mouse as a touch point, shows the cursor, starts in a window and ticks the accelerometer stand-ins.
        using System;
        using Microsoft.Xna.Framework;
        using Microsoft.Xna.Framework.Graphics;
        using Microsoft.Xna.Framework.Input;
        using Microsoft.Xna.Framework.Input.Touch;
        using XnaReborn.Compat.Device;
        using Accelerometer = Microsoft.Devices.Sensors.Accelerometer;

        namespace XnaReborn.Compat.Input
        {
            /// <summary>Decides when the window must be resizable.</summary>
            internal static class WindowRules
            {
                /// <summary>True when the back buffer the game asked for is taller than the display.</summary>
                internal static bool NeedsResize(int requestedHeight, int displayHeight) => requestedHeight > displayHeight;
            }

            public sealed class DeviceInput : GameComponent
            {
                private readonly Game _game;
                private bool _firstUpdate = true;

                public DeviceInput(Game game)
                    : base(game)
                {
                    _game = game;
                    UpdateOrder = int.MinValue;
                    DeviceRuntime.InputInstalled = true;
                    EnableTouch();
                    if (Graphics() is GraphicsDeviceManager graphics)
                    {
                        // Only the request: the device does not exist yet while the game constructor runs.
                        graphics.IsFullScreen = false;
                    }
                }

                public override void Initialize()
                {
                    base.Initialize();
                    EnableTouch();
                    _game.IsMouseVisible = true;
                    if (Graphics() is GraphicsDeviceManager graphics)
                    {
                        var changed = false;
                        if (graphics.IsFullScreen)
                        {
                            graphics.IsFullScreen = false;
                            changed = true;
                        }

                        var display = GraphicsAdapter.DefaultAdapter.CurrentDisplayMode;
                        if (WindowRules.NeedsResize(graphics.PreferredBackBufferHeight, display.Height) && !_game.Window.AllowUserResizing)
                        {
                            _game.Window.AllowUserResizing = true;
                        }

                        if (changed)
                        {
                            graphics.ApplyChanges();
                        }
                    }
                }

                public override void Update(GameTime gameTime)
                {
                    if (_firstUpdate)
                    {
                        // The switches are also set here, in case the platform ignored them before the window existed.
                        EnableTouch();
                        _firstUpdate = false;
                    }

                    var seconds = (float)gameTime.ElapsedGameTime.TotalSeconds;
                    DeviceRuntime.Tilt = TiltMapper.Ease(DeviceRuntime.Tilt, TiltMapper.Target(ReadTilt()), seconds);
                    Accelerometer.TickAll(gameTime.ElapsedGameTime);
                    base.Update(gameTime);
                }

                private static void EnableTouch()
                {
                    TouchPanel.EnableMouseTouchPoint = true;
                    TouchPanel.EnableMouseGestures = true;
                }

                private GraphicsDeviceManager? Graphics() =>
                    _game.Services.GetService(typeof(IGraphicsDeviceManager)) as GraphicsDeviceManager;

                private TiltInput ReadTilt()
                {
                    if (DeviceControls.UseMouseTilt)
                    {
                        var mouse = Mouse.GetState();
                        var bounds = _game.Window.ClientBounds;
                        var halfWidth = Math.Max(1f, bounds.Width / 2f);
                        var halfHeight = Math.Max(1f, bounds.Height / 2f);
                        return new TiltInput(false, false, false, false, new Vector2((mouse.X - halfWidth) / halfWidth, (mouse.Y - halfHeight) / halfHeight));
                    }

                    var keys = Keyboard.GetState();
                    return new TiltInput(
                        AnyDown(keys, DeviceControls.MoveLeft),
                        AnyDown(keys, DeviceControls.MoveRight),
                        AnyDown(keys, DeviceControls.MoveUp),
                        AnyDown(keys, DeviceControls.MoveDown),
                        null);
                }

                private static bool AnyDown(KeyboardState keys, Keys[] any)
                {
                    foreach (var key in any)
                    {
                        if (keys.IsKeyDown(key))
                        {
                            return true;
                        }
                    }

                    return false;
                }
            }
        }
        """;
